#!/usr/bin/env python3
"""Development helper: writes time/data.js (run again only to update the map or the zone coordinates).
- world map: land outline from Natural Earth 1:110m (public domain) via the npm package world-atlas 2.0.2 (ISC),
  converted from TopoJSON to one SVG path in plate carrée (x = longitude, y = −latitude)
- zone coordinates: zone1970.tab of the IANA time zone database (public domain), from the system's tzdata"""
import hashlib
import io
import json
import os
import re
import tarfile
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
URL = "https://registry.npmjs.org/world-atlas/-/world-atlas-2.0.2.tgz"
SHA = "032e7765f2ce00edaeafec23ff22bc3b77e42987c257da944cc585b452c05b97"


def land_path():
    data = urllib.request.urlopen(URL, timeout=60).read()
    assert hashlib.sha256(data).hexdigest() == SHA, "checksum mismatch"
    topo = json.load(tarfile.open(fileobj=io.BytesIO(data)).extractfile("package/land-110m.json"))
    sx, sy = topo["transform"]["scale"]
    tx, ty = topo["transform"]["translate"]
    arcs = []
    for arc in topo["arcs"]:                      # delta-encoded, quantized
        x = y = 0
        pts = []
        for dx, dy in arc:
            x += dx; y += dy
            pts.append((x * sx + tx, y * sy + ty))
        arcs.append(pts)

    def ring(idx):
        pts = []
        for i in idx:
            a = arcs[i] if i >= 0 else arcs[~i][::-1]
            pts.extend(a if not pts else a[1:])
        return pts

    out = []
    for geom in topo["objects"]["land"]["geometries"]:
        polys = geom["arcs"] if geom["type"] == "MultiPolygon" else [geom["arcs"]]
        for poly in polys:
            for r in poly:
                # split rings where they cross the date line (else a line runs across the whole map)
                parts, cur, prev = [], [], None
                for lon, lat in ring(r):
                    p = (round(lon, 1), round(-lat, 1))
                    if prev is not None and abs(p[0] - prev[0]) > 180:
                        parts.append(cur)
                        cur = []
                    if p != prev:
                        cur.append(p)
                    prev = p
                parts.append(cur)
                if len(parts) > 2:              # the ring started mid-way: glue first and last piece
                    parts[0] = parts.pop() + parts[0]
                for part in parts:
                    if len(part) > 2:
                        out.append("M" + "L".join(f"{x:g} {y:g}" for x, y in part) + "Z")
    return "".join(out)


def zones():
    res = {}
    with open("/usr/share/zoneinfo/zone1970.tab", encoding="utf-8") as fh:
        for line in fh:
            if line.startswith("#") or not line.strip():
                continue
            cc, coord, tz = line.rstrip("\n").split("\t")[:3]
            m = re.match(r"([+-])(\d{2})(\d{2})(\d{2})?([+-])(\d{3})(\d{2})(\d{2})?$", coord)
            lat = (int(m[2]) + int(m[3]) / 60 + int(m[4] or 0) / 3600) * (1 if m[1] == "+" else -1)
            lon = (int(m[6]) + int(m[7]) / 60 + int(m[8] or 0) / 3600) * (1 if m[5] == "+" else -1)
            res[tz] = [round(lat, 2), round(lon, 2), cc.split(",")[0]]
    return res


if __name__ == "__main__":
    path = land_path()
    z = zones()
    with open(os.path.join(HERE, "data.js"), "w", encoding="utf-8") as fh:
        fh.write("/* Generated by make_data.py – land: Natural Earth 1:110m (public domain) via world-atlas 2.0.2 (ISC);\n"
                 "   zone coordinates: IANA tz database zone1970.tab (public domain). */\n")
        fh.write("window.WORLD_LAND = " + json.dumps(path) + ";\n")
        fh.write("window.ZONE_COORDS = " + json.dumps(z, separators=(",", ":")) + ";\n")
    print("data.js:", len(path) // 1024, "KB path,", len(z), "zones")
